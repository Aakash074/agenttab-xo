// Converts the cashc artifact's ASM (contracts/AgentTab.json) into CashASM for the XO template.
// cashc prints data pushes as bare hex; CashASM needs them as <0x..> pushes. Opcodes stay as they are.
// Output: src/agenttab-cashasm.ts. test/template.test.ts checks the CashASM compiles to the exact cashc bytecode.
import { readFileSync, writeFileSync } from 'node:fs';

const artifact = JSON.parse(readFileSync('contracts/AgentTab.json', 'utf8'));
const tokens: string[] = artifact.bytecode.split(' ');
const cashAsm = tokens.map((t) => (t.startsWith('OP_') ? t : `<0x${t}>`)).join(' ');
const out = `// GENERATED by scripts/gen-cashasm.ts from contracts/AgentTab.json (cashc ${artifact.compiler.version}). Do not edit.
// The AgentTab covenant body exactly as cashc compiled it, without the constructor-argument pushes.
export const AGENTTAB_CONTRACT_CASHASM =
    '${cashAsm}';

export const AGENTTAB_CASHC_VERSION = '${artifact.compiler.version}';
`;
writeFileSync('src/agenttab-cashasm.ts', out);
console.log(`wrote src/agenttab-cashasm.ts (${tokens.length} tokens)`);
